CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) DEFAULT NULL,
  is_profile_complete TINYINT(1) DEFAULT 0,
  user_type VARCHAR(50) DEFAULT NULL,
  freelancer_id INT DEFAULT NULL,
  founder_id INT DEFAULT NULL,
  cofounder_id INT DEFAULT NULL,
  credibility_badge VARCHAR(50) DEFAULT 'none',
  credibility_score INT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  blue_tick_status ENUM('none','pending','approved','rejected') DEFAULT 'none',
  blue_tick_verified TINYINT(1) DEFAULT 0,
  green_tick_verified TINYINT(1) DEFAULT 0,
  golden_tick_verified TINYINT(1) DEFAULT 0,
  golden_tick_month VARCHAR(7) DEFAULT NULL,
  last_onboarding_reminder_at TIMESTAMP DEFAULT NULL,
  onboarding_reminder_count INT DEFAULT 0,
  google_id VARCHAR(255) UNIQUE DEFAULT NULL,
  github_id VARCHAR(255) UNIQUE DEFAULT NULL,
  whatsapp_number VARCHAR(20) DEFAULT NULL,
  whatsapp_opt_in TINYINT(1) DEFAULT 0
);
