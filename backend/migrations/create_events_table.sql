CREATE TABLE IF NOT EXISTS promoted_events (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL,
    plan_name VARCHAR(100) NOT NULL,
    extra_emails INT DEFAULT 0,
    extra_whatsapp INT DEFAULT 0,
    final_amount DECIMAL(10, 2) NOT NULL,
    event_name VARCHAR(255) NOT NULL,
    target_audience JSON NOT NULL,
    event_date DATE NOT NULL,
    event_time TIME NOT NULL,
    location VARCHAR(255) NOT NULL,
    registration_deadline DATE NOT NULL,
    registration_link VARCHAR(255) NOT NULL,
    organizer_name VARCHAR(255),
    organizer_number VARCHAR(50),
    organizer_email VARCHAR(255),
    brief TEXT NOT NULL,
    flyer_url VARCHAR(255) NOT NULL,
    razorpay_order_id VARCHAR(255),
    razorpay_payment_id VARCHAR(255),
    payment_status ENUM('pending', 'completed', 'failed') DEFAULT 'pending',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
